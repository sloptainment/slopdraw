// Generates tests/powerstroke_body_fixtures.h: slopfont's pre-union power-stroke body contours (one per skeleton segment).
// segments/pieces/body are private in powerstroke.ts, so a throwaway copy that also exports them is imported; the original stays verbatim.
// paper is only used by union(), which is never called here, so a stub stands in and npm install is not needed.
// Run: node oracle/gen_bodies.ts > tests/powerstroke_body_fixtures.h
import { readFileSync, writeFileSync, rmSync } from 'node:fs';
(globalThis as any).paper = { project: {} };
const dir = new URL('./core/geometry/', import.meta.url), probe = new URL('powerstroke_probe.ts', dir);
writeFileSync(probe, readFileSync(new URL('powerstroke.ts', dir), 'utf8') + '\nexport { segments, pieces, body };\n');
const { segments, pieces, body, widthSpans, offsetAt, segCount } = await import(probe.href).finally(() => rmSync(probe));

const cases = [
  { name: 'straight', closed: false, knots: [{ t: 0, width: 10 }, { t: 1, width: 10 }], nodes: [{ x: 0, y: 0 }, { x: 100, y: 0 }] },
  { name: 'corner_lines', closed: false, knots: [{ t: 1, width: 12 }], nodes: [{ x: 0, y: 0 }, { x: 60, y: 0 }, { x: 60, y: 50 }] },
  { name: 'curved', closed: false, knots: [{ t: 0.5, width: 8 }, { t: 1.5, width: 16 }],
    nodes: [{ x: 0, y: 0, out: { x: 30, y: 60 } }, { x: 100, y: 0, in: { x: 70, y: -60 }, out: { x: 130, y: 50 } }, { x: 180, y: 0, in: { x: 150, y: 50 } }] },
  { name: 'closed', closed: true, knots: [{ t: 0.5, width: 10 }, { t: 2.2, width: 18 }],
    nodes: [{ x: 0, y: 0, in: { x: -20, y: 40 }, out: { x: 40, y: -30 } }, { x: 120, y: 0, in: { x: 80, y: -30 }, out: { x: 140, y: 40 } }, { x: 60, y: 90, in: { x: 120, y: 80 }, out: { x: 10, y: 90 } }] },
];
const pt = (p: { x: number; y: number }) => `{${p.x}, ${p.y}}`;
const cubic = (c: { x: number; y: number }[]) => `Cubic{{${c.map(pt).join(', ')}}}`;
console.log('// Generated by oracle/gen_bodies.ts from slopfont core/geometry/powerstroke.ts (pre-union bodies, cubic, zero caps). Do not edit by hand.');
console.log('struct BodyFixture { const char* name; bool closed; std::vector<Cubic> skeleton; std::vector<WidthKnot> knots; std::vector<std::vector<Cubic>> bodies; };');
console.log('static const std::vector<BodyFixture> kBodyFixtures = {');
for (const c of cases) {
  const sub = { closed: c.closed, nodes: c.nodes }, power = { knots: c.knots, interpolator: 'cubic', startCap: 'zero', endCap: 'zero' };
  const segs = segments(sub), n = segCount(sub), spans = widthSpans(power, n, c.closed), w = (t: number) => offsetAt(spans, t);
  const cuts = [...new Set(spans.flatMap((sp: any) => [sp[0].x, sp[3].x]))].sort((a: any, b: any) => a - b);
  const bodies = segs.map((seg: any) => {
    const ns = body(pieces(seg, cuts.filter((t: any) => seg.t0 < t && t < seg.t1), w), w).nodes;
    return ns.map((a: any, i: number) => { const b = ns[(i + 1) % ns.length]; return [a, a.out ?? a, b.in ?? b, b]; });
  });
  console.log(`  {"${c.name}", ${c.closed}, {${segs.map((s: any) => cubic(s.c)).join(', ')}}, {${c.knots.map(k => `{${k.t}, ${k.width}}`).join(', ')}}, {`);
  console.log(bodies.map((b: any) => `    {${b.map(cubic).join(', ')}}`).join(',\n') + '}},');
}
console.log('};');
