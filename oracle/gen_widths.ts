// Generates tests/powerstroke_fixtures.h: slopfont's widthAt (cubic interpolator, zero caps) sampled over path time.
// paper is only used by union(), which widthAt never calls, so a stub stands in and npm install is not needed.
// Run: node oracle/gen_widths.ts > tests/powerstroke_fixtures.h
(globalThis as any).paper = { project: {} };
const { widthAt } = await import('./core/geometry/powerstroke.ts');

const cases = [
  { name: 'open_middle_knot', n: 3, closed: false, knots: [{ t: 1.5, width: 10 }] },
  { name: 'open_knots_at_ends', n: 2, closed: false, knots: [{ t: 0, width: 8 }, { t: 2, width: 8 }] },
  { name: 'open_three_knots', n: 4, closed: false, knots: [{ t: 0.5, width: 4 }, { t: 2, width: 12 }, { t: 3.25, width: 6 }] },
  { name: 'closed_two_knots', n: 4, closed: true, knots: [{ t: 1, width: 6 }, { t: 3, width: 14 }] },
];
console.log('// Generated by oracle/gen_widths.ts from slopfont core/geometry/powerstroke.ts widthAt (cubic, zero caps). Do not edit by hand.');
console.log('struct WidthFixture { const char* name; int n; bool closed; std::vector<WidthKnot> knots; std::vector<std::array<double, 2>> out; };  // out rows: {t, full width}');
console.log('static const std::vector<WidthFixture> kWidthFixtures = {');
for (const c of cases) {
  const rows: string[] = [];
  for (let t = 0; t <= c.n + 1e-9; t += 0.125) rows.push(`{${t}, ${widthAt({ knots: c.knots, interpolator: 'cubic', startCap: 'zero', endCap: 'zero' }, t, c.n, c.closed)}}`);
  console.log(`  {"${c.name}", ${c.n}, ${c.closed}, {${c.knots.map(k => `{${k.t}, ${k.width}}`).join(', ')}}, {`);
  console.log(`    ${rows.join(', ')}}},`);
}
console.log('};');
